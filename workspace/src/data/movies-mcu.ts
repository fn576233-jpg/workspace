import type { Movie, MovieStatus, UniverseId } from '../types'
import { THEMES, type ThemeKey } from './themes'
import { TRAILERS } from './trailers'

interface FilmInput {
  id: string
  title: string
  releaseDate: string
  runtime: number
  rating: number
  director: string
  genres: string[]
  synopsis: string
  cast: string[]
  characters: string[]
  franchise: string
  universe: UniverseId
  theme: ThemeKey
  motif: Movie['art']['motif']
  trailerKey?: string
  status?: MovieStatus
}

function film(f: FilmInput): Movie {
  return {
    id: f.id,
    title: f.title,
    releaseDate: f.releaseDate,
    year: new Date(f.releaseDate).getUTCFullYear(),
    runtime: f.runtime,
    rating: f.rating,
    director: f.director,
    genres: f.genres,
    synopsis: f.synopsis,
    cast: f.cast,
    characters: f.characters,
    franchise: f.franchise,
    universe: f.universe,
    trailer: f.trailerKey ? TRAILERS[f.trailerKey]?.id : undefined,
    status: f.status ?? 'released',
    theme: THEMES[f.theme],
    art: { motif: f.motif, seed: f.id },
  }
}

